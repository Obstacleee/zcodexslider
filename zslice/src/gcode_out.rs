//! Zortrax command stream -> standard Marlin G-code (relative extrusion), so that Z-Suite files can be
//! inspected or printed with other tools, and so that the importer can be round-trip tested.

use std::fmt::Write;

use zcodex2::{Command, Record};

use crate::toolpath::role;

fn type_name(r: u8) -> Option<&'static str> {
    Some(match r {
        role::OUTER | role::FIRST_CONTOUR => "External perimeter",
        role::INNER => "Perimeter",
        role::INFILL => "Internal infill",
        role::TOP => "Top solid infill",
        role::BOTTOM | role::FIRST_FILL => "Solid infill",
        role::BRIDGE => "Bridge infill",
        role::SUPPORT_CONTOUR | role::SUPPORT_INFILL => "Support material",
        role::INTERFACE_INFILL => "Support material interface",
        role::BRIM => "Skirt/Brim",
        role::RAFT | role::RAFT_BOTTOM | role::RAFT_GRID | role::RAFT_INTERFACE => "Raft",
        _ => return None,
    })
}

/// Converts records to G-code. Units: µm -> mm, E in µm of filament -> mm.
pub fn records_to_gcode(records: &[Record], generator: &str) -> String {
    let mut g = String::new();
    let _ = writeln!(g, "; generated by {generator} from a Zortrax .zcodex2 command stream");
    let _ = writeln!(g, "G21\nG90\nM83");
    let mut feed: i32 = 0;
    let mut last_type: Option<&'static str> = None;
    let mm = |v: i32| format!("{:.3}", v as f64 / 1000.0);
    for r in records {
        match r.decode() {
            Command::SetPosition(m) => {
                let mut axes = String::new();
                for (v, a) in [(m.x, 'X'), (m.y, 'Y'), (m.z, 'Z')] {
                    if let Some(v) = v {
                        let _ = write!(axes, " {a}{}", mm(v));
                    }
                }
                if m.e.is_some() {
                    axes.push_str(" E0");
                }
                if !axes.is_empty() {
                    let _ = writeln!(g, "G92{axes}");
                }
            }
            Command::BedTemp(t) => {
                let _ = writeln!(g, "M140 S{t}");
            }
            Command::NozzleTemp { temp, .. } => {
                let _ = writeln!(g, "M104 S{temp}");
            }
            Command::Home(a) => {
                let mut ax = String::new();
                if a.has(1) {
                    ax.push_str(" X");
                }
                if a.has(2) {
                    ax.push_str(" Y");
                }
                if a.has(4) {
                    ax.push_str(" Z");
                }
                let _ = writeln!(g, "G28{ax}");
            }
            Command::Feedrate(f) => feed = f,
            Command::Move(m) => {
                if m.role == 255 && m.fan2.is_some() {
                    let _ = writeln!(g, "M106 S{}", m.fan2.unwrap());
                    continue;
                }
                if let Some(t) = type_name(m.role) {
                    if last_type != Some(t) {
                        let _ = writeln!(g, ";TYPE:{t}");
                        last_type = Some(t);
                    }
                }
                let mut line = String::from("G1");
                for (v, a) in [(m.x, 'X'), (m.y, 'Y'), (m.z, 'Z')] {
                    if let Some(v) = v {
                        let _ = write!(line, " {a}{}", mm(v));
                    }
                }
                if let Some(e) = m.e {
                    let _ = write!(line, " E{}", mm(e));
                }
                let _ = writeln!(g, "{line} F{feed}");
            }
            Command::Rapid(m) => {
                let mut line = String::from("G0");
                for (v, a) in [(m.x, 'X'), (m.y, 'Y'), (m.z, 'Z')] {
                    if let Some(v) = v {
                        let _ = write!(line, " {a}{}", mm(v));
                    }
                }
                let _ = writeln!(g, "{line} F{feed}");
            }
            Command::Dwell(ms) => {
                let _ = writeln!(g, "G4 P{ms}");
            }
            Command::ChamberTemp(layer) => {
                let _ = writeln!(g, ";LAYER_CHANGE\n;LAYER:{layer}");
            }
            Command::Progress(p) => {
                let _ = writeln!(g, "M73 P{p}");
            }
            Command::EndProgram => {
                let _ = writeln!(g, "M84");
            }
            _ => {}
        }
    }
    g
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::emit::emit;
    use crate::import::parse_gcode;
    use crate::settings::Settings;
    use crate::slicer::cube_mesh;
    use crate::toolpath::plan;

    /// plan -> records -> G-code -> importer must preserve layers, filament and time.
    #[test]
    fn roundtrip_through_gcode_preserves_the_print() {
        let mut s = Settings::default();
        s.support = false;
        let mesh = cube_mesh(80.0, 80.0, 12.0);
        let p = plan(&mesh, &s).unwrap();
        let e = emit(&p, &s).unwrap();
        let text = records_to_gcode(&e.records, "test");
        assert!(text.contains(";TYPE:External perimeter") && text.contains(";LAYER:0"));
        let imp = parse_gcode(&text, &s).unwrap();
        let (a, b) = (e.filament_mm, imp.emitted.filament_mm);
        assert!((a - b).abs() / a < 0.01, "filament {a} vs {b}");
        let (ta, tb) = (e.print_time_s, imp.emitted.print_time_s);
        assert!((ta - tb).abs() / ta < 0.15, "time {ta} vs {tb}");
        let layers_direct = p.layers.len() as i64;
        let layers_back = imp.layers.len() as i64;
        // the importer starts at the first extruding layer and counts model + raft layers alike
        assert!((layers_direct - layers_back).abs() <= 1, "{layers_direct} vs {layers_back}");
        // bounding boxes agree to 1 mm
        for k in [0usize, 1, 3, 4] {
            assert!((e.bbox[k] - imp.emitted.bbox[k]).abs() < 1000, "bbox {k}: {} vs {}", e.bbox[k], imp.emitted.bbox[k]);
        }
    }
}
